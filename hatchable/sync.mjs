// Prepares hatchable/ for upload: shared server logic into lib/, client build + district map into public/.
// Hatchable has no build step and can't import JSON, so this does both here. Run: node hatchable/sync.mjs
import { execSync } from 'node:child_process'
import { cpSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const here = `${root}hatchable`

const core = readFileSync(`${root}server/core.js`, 'utf8')
const from = "import drugs from '../data/reference/drugs.json' with { type: 'json' }"
if (!core.includes(from)) throw new Error('server/core.js drugs import changed; update sync.mjs')
writeFileSync(`${here}/lib/core.js`, '// GENERATED by hatchable/sync.mjs from server/core.js. Edit that file instead.\n' + core.replace(from, "import drugs from './drugs.js'"))
// Only the fields core.js reads, to keep the hand-uploaded lib file small
const drugs = JSON.parse(readFileSync(`${root}data/reference/drugs.json`, 'utf8'))
  .map(({ generic_name, common_indian_brands, common_adrs, serious_adrs }) => ({ generic_name, common_indian_brands, common_adrs, serious_adrs }))
writeFileSync(`${here}/lib/drugs.js`, '// GENERATED by hatchable/sync.mjs from data/reference/drugs.json.\nexport default ' + JSON.stringify(drugs) + '\n')

execSync('npm run build --prefix client', { cwd: root, stdio: 'inherit' })
rmSync(`${here}/public`, { recursive: true, force: true })
cpSync(`${root}client/dist`, `${here}/public`, { recursive: true })
cpSync(`${root}data/geo/india_districts.min.geojson`, `${here}/public/districts.geojson`)
console.log('hatchable/ ready')
