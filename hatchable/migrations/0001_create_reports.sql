-- Submitted reports. Seed rows are generated in code (lib/core.js seedRows) so the demo spike always sits in the last 7 days.
-- Ids start at 100000 so they never collide with seed ids 1..430.
CREATE TABLE reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
  created_at TIMESTAMP NOT NULL,
  raw_text TEXT,
  language TEXT,
  drug_name TEXT,
  generic_name TEXT,
  reaction TEXT,
  reaction_english TEXT,
  severity TEXT NOT NULL CHECK (severity IN ('mild', 'moderate', 'severe')),
  onset TEXT,
  outcome TEXT,
  age INTEGER,
  gender TEXT,
  district TEXT,
  state TEXT,
  confidence REAL,
  followup_status TEXT
);
